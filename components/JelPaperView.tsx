function StatusBadge({ status }: { status: JelPaper['status'] }) {
  const map: Record<string, { label: string; className: string }> = {
    queued:  { label: 'Queued',  className: 'bg-slate-100 text-slate-600 border-slate-200' },
    running: { label: 'Drafting…', className: 'bg-amber-50 text-amber-700 border-amber-200 animate-pulse' },
    done:    { label: 'Ready',   className: 'bg-emerald-50 text-emerald-700 border-emerald-200' },
    error:   { label: 'Error',   className: 'bg-red-50 text-red-700 border-red-200' },
  };
  const { label, className } = map[status] ?? map.queued;
  return (
    <span className={`rounded-full px-2.5 py-0.5 text-[11px] font-semibold border ${className}`}>
      {label}
    </span>
  );
}

// ---------------------------------------------------------------------------
// Citation numbering — build workId → number map from bibliography
// ---------------------------------------------------------------------------

function buildCitationMap(bibliography: JelBibEntry[]): Map<string, number> {
  const map = new Map<string, number>();
  for (const entry of bibliography) {
    map.set(entry.workId, entry.number);
  }
  return map;
}

// ---------------------------------------------------------------------------
// Section renderer — JEL author-year style
//
// Qwen writes "Author (year) [workId] find that..."
// [workId] tokens are stripped from display — the author-year text is the
// citation. The bibliography at the bottom provides full references.
// ---------------------------------------------------------------------------

function SectionBody({ body, citationMap: _citationMap }: { body: string; citationMap: Map<string, number> }) {
  // Strip all [workId] tokens; keep everything else as-is
  const cleaned = body.replace(/\s*\[[^\]]{3,}\]/g, '');
  return (
    <div className="text-[14px] text-slate-800 leading-relaxed whitespace-pre-wrap font-serif">
      {cleaned}
    </div>
  );
}

