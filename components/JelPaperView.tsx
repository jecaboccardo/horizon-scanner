/** "Drafting sections… X of N complete" where X never exceeds N.
 *  N is the outline length + 1 (the appended "Critical Assessment" section),
 *  but the pipeline can persist more sections than a stale/confirmed outline
 *  predicted — so we take max(expected, drafted) to avoid the impossible
 *  "8 of 7". With no outline yet, show the raw count without a fraction. */
function draftProgressLabel(paper: JelPaper): string {
  const drafted = paper.sections?.length ?? 0;
  const outlineLen = paper.outline?.sections?.length ?? 0;
  if (!outlineLen) return `Drafting sections… ${drafted} so far`;
  const total = Math.max(outlineLen + 1, drafted); // +1 = appended Critical Assessment
  return `Drafting sections… ${drafted} of ${total} complete`;
}

