function buildPaperText(paper: JelPaper): string {
  const lines: string[] = [];
  const bibMap = new Map((paper.bibliography ?? []).map(e => [e.workId, e.number]));

  lines.push(paper.outline?.title ?? paper.query);
  lines.push(`Generated by Horizon Scanner — IADB Evidence Intelligence Platform`);
  lines.push(`Query: ${paper.query}`);
  lines.push(`Generated: ${paper.completedAt ? new Date(paper.completedAt).toLocaleString() : 'pending'}`);
  lines.push(`Words: ${paper.wordCount?.toLocaleString() ?? '—'} · Citations: ${paper.citationCount ?? '—'}`);
  lines.push('');

  if (paper.outline?.abstract) {
    lines.push('ABSTRACT');
    lines.push(paper.outline.abstract);
    lines.push('');
  }

  for (const section of paper.sections) {
    lines.push(`§${section.number}  ${section.heading}`);
    lines.push('');
    // Strip [workId] tokens — author-year text in prose is the citation
    const body = section.body.replace(/\s*\[[^\]]{3,}\]/g, '');
    lines.push(body);
    lines.push('');
  }

  if ((paper.bibliography ?? []).length > 0) {
    lines.push('EVIDENCE TABLE');
    lines.push('');
    for (const e of paper.bibliography) {
      const doi = e.doi ? ` https://doi.org/${e.doi}` : '';
      lines.push(`${e.number}. ${e.authors} (${e.year ?? 'n.d.'}). ${e.title}.${e.venue ? ` ${e.venue}.` : ''}${doi}${e.cited ? ' [cited]' : ''}${e.unverified ? ' [user-supplied, unverified]' : ''}`);
    }
    lines.push('');
  }

  return lines.join('\n');
}

function downloadText(content: string, filename: string) {
  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

