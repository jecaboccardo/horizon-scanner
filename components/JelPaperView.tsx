function Bibliography({ entries }: { entries: JelBibEntry[] }) {
  const [expanded, setExpanded] = useState(false);
  const VISIBLE = 15;
  const shown = expanded ? entries : entries.slice(0, VISIBLE);

  if (entries.length === 0) return null;

  const citedCount = entries.filter(e => e.cited).length;

  return (
    <section id="jel-section-bibliography" className="mb-10 scroll-mt-4">
      <h2 className="text-lg font-bold text-slate-900 mb-1 pb-2 border-b border-slate-100">
        Evidence Table
      </h2>
      <p className="text-[12px] text-slate-500 mb-4">
        All {entries.length} evidence papers, in the same order as the brief’s evidence table
        {citedCount > 0 && <> · {citedCount} cited in this paper</>}
      </p>
      <div className="space-y-2">
        {shown.map((e) => {
          const doiUrl = e.doi ? `https://doi.org/${e.doi}` : null;
          return (
            <div key={e.workId} className={`flex gap-3 text-[13px] leading-snug ${e.cited ? 'text-slate-700' : 'text-slate-400'}`}>
              <span className={`shrink-0 font-semibold tabular-nums w-7 text-right ${e.cited ? 'text-indigo-600' : 'text-slate-300'}`}>{e.number}.</span>
              <span>
                {e.authors} ({e.year ?? 'n.d.'}). {' '}
                {doiUrl ? (
                  <a href={doiUrl} target="_blank" rel="noopener noreferrer"
                    className="italic hover:text-indigo-700 hover:underline">
                    {e.title}
                  </a>
                ) : (
                  <span className="italic">{e.title}</span>
                )}
                {e.venue && <span className="text-slate-500"> — {e.venue}</span>}
                {e.cited && <span className="ml-1.5 rounded-full bg-indigo-50 border border-indigo-100 text-indigo-600 px-1.5 py-0.5 text-[10px] font-semibold align-middle">cited</span>}
                {e.unverified && <span className="ml-1.5 rounded-full bg-amber-50 border border-amber-200 text-amber-700 px-1.5 py-0.5 text-[10px] font-semibold align-middle">user-supplied · unverified</span>}
                {doiUrl && (
                  <a href={doiUrl} target="_blank" rel="noopener noreferrer"
                    className="ml-1 text-[11px] text-indigo-500 hover:underline">
                    ↗
                  </a>
                )}
              </span>
            </div>
          );
        })}
      </div>
      {entries.length > VISIBLE && (
        <button
          onClick={() => setExpanded(v => !v)}
          className="mt-3 text-xs font-semibold text-teal-600 hover:text-teal-800 transition"
        >
          {expanded ? `Collapse` : `Show all ${entries.length} papers`}
        </button>
      )}
    </section>
  );
}

// ---------------------------------------------------------------------------
// Table of contents
// ---------------------------------------------------------------------------

function TableOfContents({
  sections,
  activeNumber,
  onSelect,
}: {
  sections: JelSection[];
  activeNumber: string | null;
  onSelect: (n: string) => void;
}) {
  return (
    <nav className="space-y-0.5">
      {sections.map((s) => (
        <button
          key={s.number}
          onClick={() => onSelect(s.number)}
          className={`w-full text-left px-3 py-1.5 rounded-lg text-xs transition ${
            activeNumber === s.number
              ? 'bg-indigo-50 text-indigo-700 font-semibold'
              : 'text-slate-600 hover:bg-slate-50 hover:text-slate-900'
          }`}
        >
          <span className="text-slate-400 mr-1.5 tabular-nums">§{s.number}</span>
          {s.heading}
          {s.wordCount > 0 && (
            <span className="ml-1.5 text-slate-300 text-[10px]">{s.wordCount.toLocaleString()}w</span>
          )}
        </button>
      ))}
    </nav>
  );
}

